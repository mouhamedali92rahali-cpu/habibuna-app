import json,re
M=json.load(open('data/batch20/matn_src.json'))
def clean(t):
    t=t.replace('‏','').replace('صلى الله عليه وسلم','ﷺ').replace('ـ رضى الله عنه ـ ','')
    out=[];o=True
    for ch in t:
        if ch=='"': out.append('«' if o else '»'); o=not o
        else: out.append(ch)
    t=''.join(out)
    t=re.sub(r'\s*\.\s*','. ',t); t=re.sub(r'\s+',' ',t).replace(' ،','،').strip()
    if t.count('«')>t.count('»'): t+='»'
    return t.rstrip('. ')+'.' if not t.endswith('»') else t
