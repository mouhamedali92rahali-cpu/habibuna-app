def clean(t):
    t=t.replace('‏','').replace('صلى الله عليه وسلم','ﷺ')
    out=[];o=True
    for ch in t:
        if ch=='"': out.append('«' if o else '»'); o=not o
        else: out.append(ch)
    t=''.join(out)
    t=re.sub(r'\s*\.\s*','. ',t); t=re.sub(r'\s+',' ',t).replace(' ،','،').strip()
    if t.count('«')>t.count('»'): t+='»'
    return t
def m(*keys,sep=' … '): return sep.join(clean(M[k]) for k in keys)
