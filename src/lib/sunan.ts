import { hijriToday, type Overrides } from './hijri';

/**
 * «سنن الأيام» تحت خط الصلاة (قرار المستخدم 2026-11-12): سطر قصير بلا مصدر ظاهر، ولمسه يُظهر الحديث بمصدره ودرجته.
 * الصيام يُنبَّه عليه في اليوم السابق («غدًا …»). مسودة للتجربة؛ النصوص من نسخ fawazahmed0 (الترمذي 745 و761، مسلم 854 و1134 و1162 و1164، البخاري 969).
 */
export interface Sunna { id: string; line: string; matn: string; narr: string; source: string; grade: string }

const S = {
  mon: { matn: 'كان النبي ﷺ يتحرّى صوم الاثنين والخميس.', narr: 'عائشة', source: 'الترمذي (745)', grade: 'حسن — الترمذي: حسن غريب' },
  bid: { matn: '«يا أبا ذرّ، إذا صمت من الشهر ثلاثة أيام فصم ثلاث عشرة وأربع عشرة وخمس عشرة».', narr: 'أبي ذرّ', source: 'الترمذي (761)', grade: 'حسن — الترمذي' },
  arafa: { matn: '«صيام يوم عرفة أحتسب على الله أن يكفّر السنة التي قبله والسنة التي بعده، وصيام يوم عاشوراء أحتسب على الله أن يكفّر السنة التي قبله».', narr: 'أبي قتادة', source: 'مسلم (1162)', grade: 'صحيح — مسلم' },
  tasua: { matn: '«لئن بقيت إلى قابل لأصومنّ التاسع».', narr: 'ابن عباس', source: 'مسلم (1134)', grade: 'صحيح — مسلم' },
  shawwal: { matn: '«من صام رمضان ثم أتبعه ستًّا من شوّال كان كصيام الدهر».', narr: 'أبي أيوب الأنصاري', source: 'مسلم (1164)', grade: 'صحيح — مسلم' },
  ashr: { matn: '«ما العمل في أيام العشر أفضل من العمل في هذه». قالوا: ولا الجهاد؟ قال: «ولا الجهاد، إلا رجل خرج يخاطر بنفسه وماله فلم يرجع بشيء».', narr: 'ابن عباس', source: 'البخاري (969)', grade: 'صحيح — البخاري' },
  jumua: { matn: '«خير يوم طلعت عليه الشمس يوم الجمعة، فيه خُلق آدم، وفيه أُدخل الجنة، وفيه أُخرج منها».', narr: 'أبي هريرة', source: 'مسلم (854)', grade: 'صحيح — مسلم' },
};

const HM = ['محرّم', 'صفر', 'ربيع الأول', 'ربيع الآخر', 'جمادى الأولى', 'جمادى الآخرة', 'رجب', 'شعبان', 'رمضان', 'شوّال', 'ذو القعدة', 'ذو الحجة'];
const dm = (s: string): { d: number; m: number } | null => {
  const r = /^(\d+) (.+) \d+ هـ$/.exec(s);
  if (!r) return null;
  const m = HM.indexOf(r[2]) + 1;
  return m ? { d: +r[1], m } : null;
};
const WD = ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'];

export function sunanFor(now: Date, over: Overrides = {}): Sunna[] {
  const tmr = new Date(now); tmr.setDate(tmr.getDate() + 1);
  const h0 = dm(hijriToday(now, over).hijri), h1 = dm(hijriToday(tmr, over).hijri);
  const out: Sunna[] = [];
  // لا تنبيه على صيام غدٍ إن كان رمضان أو عيدًا أو من أيام التشريق
  const noFast = !h1 || h1.m === 9 || (h1.m === 10 && h1.d === 1) || (h1.m === 12 && h1.d >= 10 && h1.d <= 13);
  if (h1 && !noFast) {
    if (h1.m === 12 && h1.d === 9) out.push({ id: 'arafa', line: 'غدًا يوم عرفة: صيامه يكفّر السنة التي قبله والتي بعده', ...S.arafa });
    if (h1.m === 1 && h1.d === 9) out.push({ id: 'tasua', line: 'غدًا التاسع من محرّم: «لئن بقيت إلى قابل لأصومنّ التاسع»', ...S.tasua });
    if (h1.m === 1 && h1.d === 10) out.push({ id: 'ashura', line: 'غدًا عاشوراء: صيامه يكفّر السنة التي قبله', ...S.arafa });
    if (h1.d >= 13 && h1.d <= 15) out.push({ id: 'bid', line: h1.d === 13 ? 'غدًا أول الأيام البيض: كان ﷺ يوصي بصيامها' : 'غدًا من الأيام البيض: كان ﷺ يوصي بصيامها', ...S.bid });
    const w = tmr.getDay();
    if (w === 1 || w === 4) out.push({ id: 'mon', line: `غدًا ${WD[w]}: كان النبي ﷺ يتحرّى صيامه`, ...S.mon });
  }
  if (h0 && h0.m === 10 && h0.d >= 2 && h0.d <= 29) out.push({ id: 'shawwal', line: 'ستّ من شوّال: من صامها بعد رمضان كان كصيام الدهر', ...S.shawwal });
  if (h0 && h0.m === 12 && h0.d >= 1 && h0.d <= 9) out.push({ id: 'ashr', line: 'أيام العشر: ما العمل الصالح في أيام أفضل منه فيها', ...S.ashr });
  if (now.getDay() === 5) out.push({ id: 'jumua', line: 'اليوم الجمعة: خير يوم طلعت عليه الشمس', ...S.jumua });
  return out;
}

/** رمضان اليوم؟ (لعبارة «هذا وقت الصلاة، لا وقت الإمساك» تحت الفجر) */
export const isRamadan = (now: Date, over: Overrides = {}) => dm(hijriToday(now, over).hijri)?.m === 9;
